USE QuanLyKyTucXa;
DROP PROCEDURE IF EXISTS ktx_upgrade_003;
DELIMITER //
CREATE PROCEDURE ktx_upgrade_003()
BEGIN
 IF NOT EXISTS(SELECT 1 FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='DienNuoc' AND COLUMN_NAME='NgayLap') THEN
  ALTER TABLE DienNuoc ADD COLUMN NgayLap DATE NULL;
  UPDATE DienNuoc SET NgayLap=DATE_ADD(Ky,INTERVAL 1 MONTH);
  ALTER TABLE DienNuoc MODIFY NgayLap DATE NOT NULL;
 END IF;
 IF NOT EXISTS(SELECT 1 FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='ViPham' AND COLUMN_NAME='HinhThuc') THEN
  ALTER TABLE ViPham ADD COLUMN HinhThuc ENUM('NHAC_NHO','HANH_CHINH','DINH_CHI') NOT NULL DEFAULT 'NHAC_NHO';
  UPDATE ViPham SET HinhThuc='HANH_CHINH' WHERE TienPhat>0;
 END IF;
 IF NOT EXISTS(SELECT 1 FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='XeVeThang' AND COLUMN_NAME='NgayKetThuc') THEN
  ALTER TABLE XeVeThang ADD COLUMN NgayKetThuc DATE NULL;
 END IF;
 ALTER TABLE HopDong MODIFY TrangThai ENUM('HIEU_LUC','DA_THANH_LY','DINH_CHI') NOT NULL DEFAULT 'HIEU_LUC';
END //
DELIMITER ;
CALL ktx_upgrade_003();
DROP PROCEDURE ktx_upgrade_003;

CREATE TABLE IF NOT EXISTS DinhChiLuuTru (
 MaSV VARCHAR(10) PRIMARY KEY, MaViPham INT NOT NULL UNIQUE, Ngay DATE NOT NULL,
 FOREIGN KEY(MaSV) REFERENCES SinhVien(MaSV), FOREIGN KEY(MaViPham) REFERENCES ViPham(ID)
);
DROP TRIGGER IF EXISTS ktx_block_suspended_room;
DROP TRIGGER IF EXISTS ktx_block_suspended_vehicle;
DELIMITER //
CREATE TRIGGER ktx_block_suspended_room BEFORE UPDATE ON SinhVien FOR EACH ROW
BEGIN
 IF NEW.MaPhong IS NOT NULL AND EXISTS(SELECT 1 FROM DinhChiLuuTru WHERE MaSV=NEW.MaSV) THEN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Sinh vien da bi dinh chi luu tru, khong duoc xep phong.';
 END IF;
END //
CREATE TRIGGER ktx_block_suspended_vehicle BEFORE INSERT ON XeVeThang FOR EACH ROW
BEGIN
 IF EXISTS(SELECT 1 FROM DinhChiLuuTru WHERE MaSV=NEW.MaSV) THEN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Sinh vien da bi dinh chi luu tru, khong duoc dang ky ve thang.';
 END IF;
END //
DELIMITER ;
