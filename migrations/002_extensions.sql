-- Chạy sau datasinhvien.sql. Không xóa hoặc thay thế dữ liệu hiện có.
USE QuanLyKyTucXa;

CREATE TABLE IF NOT EXISTS TaiKhoan (
 TenDangNhap VARCHAR(50) PRIMARY KEY,
 MatKhau VARCHAR(256) NOT NULL,
 VaiTro ENUM('ADMIN','STAFF','STUDENT') NOT NULL,
 MaSV VARCHAR(10) UNIQUE,
 FOREIGN KEY (MaSV) REFERENCES SinhVien(MaSV),
 CHECK ((VaiTro='STUDENT' AND MaSV IS NOT NULL) OR (VaiTro<>'STUDENT' AND MaSV IS NULL))
);
CREATE TABLE IF NOT EXISTS DonDangKy (
 ID INT AUTO_INCREMENT PRIMARY KEY, MaSV VARCHAR(10) NOT NULL,
 LoaiPhong VARCHAR(50) NOT NULL, NgayGui DATE NOT NULL,
 TrangThai ENUM('CHO_DUYET','DA_DUYET','TU_CHOI') NOT NULL DEFAULT 'CHO_DUYET',
 GhiChu VARCHAR(500) NOT NULL DEFAULT '',
 FOREIGN KEY (MaSV) REFERENCES SinhVien(MaSV)
);
CREATE TABLE IF NOT EXISTS HopDong (
 ID INT AUTO_INCREMENT PRIMARY KEY, MaSV VARCHAR(10) NOT NULL, MaPhong VARCHAR(10) NOT NULL,
 NgayBatDau DATE NOT NULL, NgayKetThuc DATE NOT NULL, TienCoc DECIMAL(12,2) NOT NULL,
 TrangThai ENUM('HIEU_LUC','DA_THANH_LY') NOT NULL DEFAULT 'HIEU_LUC',
 FOREIGN KEY (MaSV) REFERENCES SinhVien(MaSV), FOREIGN KEY (MaPhong) REFERENCES Phong(MaPhong),
 CHECK (NgayKetThuc>=NgayBatDau), CHECK (TienCoc>=0)
);
CREATE TABLE IF NOT EXISTS ChuyenPhong (
 ID INT AUTO_INCREMENT PRIMARY KEY, MaSV VARCHAR(10) NOT NULL,
 PhongCu VARCHAR(10), PhongMoi VARCHAR(10) NOT NULL, LyDo VARCHAR(500) NOT NULL,
 NgayGui DATE NOT NULL, TrangThai ENUM('CHO_DUYET','DA_DUYET','TU_CHOI') NOT NULL DEFAULT 'CHO_DUYET',
 FOREIGN KEY (MaSV) REFERENCES SinhVien(MaSV),
 FOREIGN KEY (PhongCu) REFERENCES Phong(MaPhong), FOREIGN KEY (PhongMoi) REFERENCES Phong(MaPhong)
);
CREATE TABLE IF NOT EXISTS SuaChua (
 ID INT AUTO_INCREMENT PRIMARY KEY, MaSV VARCHAR(10) NOT NULL, MaPhong VARCHAR(10) NOT NULL,
 MoTa VARCHAR(1000) NOT NULL, Anh VARCHAR(500) NOT NULL DEFAULT '', NgayBao DATE NOT NULL,
 TrangThai ENUM('TIEP_NHAN','DANG_XU_LY','HOAN_THANH') NOT NULL DEFAULT 'TIEP_NHAN',
 FOREIGN KEY (MaSV) REFERENCES SinhVien(MaSV), FOREIGN KEY (MaPhong) REFERENCES Phong(MaPhong)
);
CREATE TABLE IF NOT EXISTS TaiSan (
 ID INT AUTO_INCREMENT PRIMARY KEY, MaPhong VARCHAR(10) NOT NULL, TenTaiSan VARCHAR(100) NOT NULL,
 SoLuong INT NOT NULL, TinhTrang VARCHAR(200) NOT NULL, BienBan VARCHAR(1000) NOT NULL,
 NgayBanGiao DATE NOT NULL, FOREIGN KEY (MaPhong) REFERENCES Phong(MaPhong), CHECK (SoLuong>0)
);
CREATE TABLE IF NOT EXISTS DienNuoc (
 ID INT AUTO_INCREMENT PRIMARY KEY, MaPhong VARCHAR(10) NOT NULL, Ky DATE NOT NULL,
 DienCu DECIMAL(12,2) NOT NULL, DienMoi DECIMAL(12,2) NOT NULL,
 NuocCu DECIMAL(12,2) NOT NULL, NuocMoi DECIMAL(12,2) NOT NULL,
 GiaDien DECIMAL(12,2) NOT NULL, GiaNuoc DECIMAL(12,2) NOT NULL,
 UNIQUE(MaPhong,Ky), FOREIGN KEY (MaPhong) REFERENCES Phong(MaPhong),
 CHECK (DAY(Ky)=1), CHECK (DienCu>=0 AND DienMoi>=DienCu),
 CHECK (NuocCu>=0 AND NuocMoi>=NuocCu), CHECK (GiaDien>=0 AND GiaNuoc>=0)
);
-- Chốt danh sách cư dân và phần tiền khi lập điện nước, không chia lại khi chuyển phòng.
CREATE TABLE IF NOT EXISTS PhanBoDienNuoc (
 MaDienNuoc INT NOT NULL, MaSV VARCHAR(10) NOT NULL, SoTien DECIMAL(12,2) NOT NULL,
 PRIMARY KEY(MaDienNuoc,MaSV), FOREIGN KEY (MaDienNuoc) REFERENCES DienNuoc(ID),
 FOREIGN KEY (MaSV) REFERENCES SinhVien(MaSV), CHECK (SoTien>=0)
);
CREATE TABLE IF NOT EXISTS ThanhToan (
 ID INT AUTO_INCREMENT PRIMARY KEY, MaSV VARCHAR(10) NOT NULL, Ky DATE NOT NULL,
 SoTien DECIMAL(12,2) NOT NULL, NgayThanhToan DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 GhiChu VARCHAR(500) NOT NULL, FOREIGN KEY (MaSV) REFERENCES SinhVien(MaSV),
 CHECK (SoTien>0), CHECK (DAY(Ky)=1)
);
CREATE TABLE IF NOT EXISTS ThongBao (
 ID INT AUTO_INCREMENT PRIMARY KEY, TieuDe VARCHAR(200) NOT NULL, NoiDung VARCHAR(2000) NOT NULL,
 MaPhong VARCHAR(10), Han DATE NOT NULL, NgayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (MaPhong) REFERENCES Phong(MaPhong)
);
CREATE TABLE IF NOT EXISTS ViPham (
 ID INT AUTO_INCREMENT PRIMARY KEY, MaSV VARCHAR(10) NOT NULL, NgayViPham DATE NOT NULL,
 NoiDung VARCHAR(1000) NOT NULL, XuLy VARCHAR(500) NOT NULL, TienPhat DECIMAL(12,2) NOT NULL,
 FOREIGN KEY (MaSV) REFERENCES SinhVien(MaSV), CHECK (TienPhat>=0)
);

-- Lịch sử lưu trú giữ tiền phòng tháng cũ khi chuyển hoặc trả phòng.
CREATE TABLE IF NOT EXISTS LichSuLuuTru (
 ID INT AUTO_INCREMENT PRIMARY KEY, MaSV VARCHAR(10) NOT NULL, MaPhong VARCHAR(10) NOT NULL,
 NgayVao DATE NOT NULL, NgayRa DATE, DonGia DECIMAL(12,2) NOT NULL,
 FOREIGN KEY (MaSV) REFERENCES SinhVien(MaSV) ON DELETE CASCADE,
 FOREIGN KEY (MaPhong) REFERENCES Phong(MaPhong), INDEX idx_luutru_sv_ngay(MaSV,NgayVao,NgayRa)
);
INSERT INTO LichSuLuuTru(MaSV,MaPhong,NgayVao,DonGia)
 SELECT s.MaSV,s.MaPhong,s.NgayVaoKTX,p.DonGia FROM SinhVien s JOIN Phong p ON p.MaPhong=s.MaPhong
 WHERE NOT EXISTS(SELECT 1 FROM LichSuLuuTru l WHERE l.MaSV=s.MaSV);

DROP TRIGGER IF EXISTS ktx_luutru_insert;
DROP TRIGGER IF EXISTS ktx_luutru_update;
DELIMITER //
CREATE TRIGGER ktx_luutru_insert AFTER INSERT ON SinhVien FOR EACH ROW
BEGIN
 IF NEW.MaPhong IS NOT NULL THEN
  INSERT INTO LichSuLuuTru(MaSV,MaPhong,NgayVao,DonGia)
   SELECT NEW.MaSV,NEW.MaPhong,NEW.NgayVaoKTX,DonGia FROM Phong WHERE MaPhong=NEW.MaPhong;
 END IF;
END //
CREATE TRIGGER ktx_luutru_update AFTER UPDATE ON SinhVien FOR EACH ROW
BEGIN
 IF NOT (NEW.MaPhong <=> OLD.MaPhong) THEN
  UPDATE LichSuLuuTru SET NgayRa=CURRENT_DATE WHERE MaSV=NEW.MaSV AND NgayRa IS NULL;
  IF NEW.MaPhong IS NOT NULL THEN
   INSERT INTO LichSuLuuTru(MaSV,MaPhong,NgayVao,DonGia)
    SELECT NEW.MaSV,NEW.MaPhong,GREATEST(NEW.NgayVaoKTX,CURRENT_DATE),DonGia FROM Phong WHERE MaPhong=NEW.MaPhong;
  END IF;
 END IF;
END //
DELIMITER ;
